import { useEffect, useState, type DragEvent as ReactDragEvent, type ReactNode } from 'react';
import { cn } from '@/lib/utils';
import { usePanelStore, type PanelEntry, type PanelRegion } from '@/stores/panel-store';
import { useI18n } from '@/i18n';
import { panelTitle } from './panel-title';
import { useUIStore } from '@/stores/ui-store';
import { panelIcon } from './panel-icons';
import { Tooltip, TooltipContent, TooltipTrigger } from '@/components/ui/tooltip';

/**
 * Rail icon. Plugin-provided icons render as a CSS-mask stencil — the SVG's
 * alpha channel colors with `currentColor`, so plugin icons match the host's
 * lucide glyphs across themes and hover/active states (masks never execute
 * scripts either). Falls back to the vocabulary icon when the asset fails.
 *
 * Exported for the tab strip, which needs the same fallback at tab scale.
 */
export function RailIcon({
  panel,
  size = 24,
  className = 'h-6 w-6',
}: {
  panel: PanelEntry;
  /** Pixel size of the mask; lucide glyphs scale via `className`. */
  size?: number;
  className?: string;
}) {
  const [broken, setBroken] = useState(false);
  const Icon = panelIcon(panel.icon);

  useEffect(() => {
    setBroken(false);
    if (!panel.iconUrl) return;
    // Probe the asset — CSS masks fail silently, so detect via Image().
    const probe = new Image();
    probe.onerror = () => setBroken(true);
    probe.src = panel.iconUrl;
    return () => { probe.onerror = null; };
  }, [panel.iconUrl]);

  if (panel.iconUrl && !broken) {
    return (
      <span
        aria-hidden
        className="bg-current"
        // Inline size — fractional Tailwind utilities (h-4.5) may not be
        // generated by JIT; 24px matches the effective size of the lucide
        // glyphs beside it.
        style={{
          width: size,
          height: size,
          WebkitMaskImage: `url(${panel.iconUrl})`,
          maskImage: `url(${panel.iconUrl})`,
          WebkitMaskSize: 'contain',
          maskSize: 'contain',
          WebkitMaskRepeat: 'no-repeat',
          maskRepeat: 'no-repeat',
          WebkitMaskPosition: 'center',
          maskPosition: 'center',
        }}
      />
    );
  }
  return <Icon className={className} />;
}

function RailButton({ panel, region }: { panel: PanelEntry; region: PanelRegion }) {
  const { t } = useI18n();
  const title = panelTitle(panel, t);
  const focusedId = usePanelStore((s) => s.focusedId[region]);
  const openPanel = usePanelStore((s) => s.openPanel);
  const setRightPanelOpen = useUIStore((s) => s.setRightPanelOpen);
  const runtime = usePanelStore((s) => s.runtime[panel.id]);

  // Active in EITHER slot — a split region shows two panels at once and the
  // rail must light up for both.
  const active = focusedId === panel.id;
  const badge = runtime?.badge;
  const pending = runtime?.pending;
  // The rail sits beside its content column, so the indicator goes on the
  // inner edge: right edge for a left rail, left edge for a right rail.
  const isLeft = region === 'left';

  return (
    <Tooltip>
      <TooltipTrigger asChild>
        <button
          type="button"
          aria-label={title}
          aria-pressed={active}
          data-panel-id={panel.id}
          data-state={active ? 'active' : 'inactive'}
          data-pending={pending ? 'true' : undefined}
          onClick={() => {
            openPanel(panel.id, { focus: true });
            // A rail click on the right is an explicit open — surface that side.
            // The left column is toggled from the title bar and is already
            // visible whenever its rail is reachable.
            if (region === 'right') setRightPanelOpen(true);
          }}
          className={cn(
            'relative flex h-10 w-10 items-center justify-center rounded-md text-muted-foreground transition-colors',
            'hover:bg-accent hover:text-accent-foreground',
            active && 'bg-accent text-accent-foreground',
            pending && !active && 'text-foreground',
          )}
        >
          <RailIcon panel={panel} />
          {badge !== undefined && badge !== null && badge !== '' && (
            <span
              data-panel-badge
              className={cn(
                'absolute -top-0.5 min-w-[16px] rounded-full bg-primary px-1 text-[10px] font-medium leading-4 text-primary-foreground',
                isLeft ? '-left-0.5' : '-right-0.5',
              )}
            >
              {badge}
            </span>
          )}
          {pending && badge === undefined && (
            <span className={cn('absolute top-1 h-2 w-2 animate-pulse rounded-full bg-primary', isLeft ? 'left-1' : 'right-1')} />
          )}
          {active && (
            <span
              className={cn(
                'absolute top-1/2 h-5 w-0.5 -translate-y-1/2 bg-primary',
                isLeft ? 'right-0 rounded-l' : 'left-0 rounded-r',
              )}
            />
          )}
        </button>
      </TooltipTrigger>
      <TooltipContent side={isLeft ? 'right' : 'left'}>{title}</TooltipContent>
    </Tooltip>
  );
}

/**
 * Icon rail for one sidebar column: the panel switcher. Host panels and plugin
 * panels live side by side; badges/active dots stay visible even when the panel
 * body is collapsed. The plugin center is a regular rail entry (host:plugins) —
 * no separate bottom "+" launcher.
 *
 * Panels are split into two groups by `anchor`; the bottom group is pushed to
 * the far end, which is where configuration-style panels belong.
 *
 * Only the LEFT column mounts this vertical rail. The RIGHT column's launcher
 * merged into its tab strip (2026-10-16): open panels are tabs, a trailing
 * "+" picker opens everything else — a 48px rail of icons beside the slots
 * duplicated the strip one row over.
 */
export function PanelRail({
  region = 'right',
  railFooter,
}: {
  region?: PanelRegion;
  /**
   * Host actions pinned below the bottom group. Settings lives here rather than
   * in a panel entry: it opens a dialog, so it must not participate in panel
   * selection, persistence or layout.
   */
  railFooter?: ReactNode;
}) {
  const panels = usePanelStore((s) => s.panels);
  const panelOrder = usePanelStore((s) => s.panelOrder[region]);
  const setPanelOrder = usePanelStore((s) => s.setPanelOrder);
  const [dragId, setDragId] = useState<string | null>(null);
  const [dropTargetId, setDropTargetId] = useState<string | null>(null);

  // Hidden panels are openable via panel.open / events but get no rail button.
  // Display order follows the user's `panelOrder` arrangement (the same store
  // the tab strip's drag writes), registry order for entries never arranged.
  const orderIndex = new Map(panelOrder.map((id, i) => [id, i]));
  const railPanels = panels
    .filter((p) => p.region === region && !p.hidden)
    .sort((a, b) => {
      const ia = orderIndex.get(a.id) ?? Number.MAX_SAFE_INTEGER;
      const ib = orderIndex.get(b.id) ?? Number.MAX_SAFE_INTEGER;
      return ia === ib ? (a.order ?? 0) - (b.order ?? 0) : ia - ib;
    });

  const topGroup = railPanels.filter((p) => p.anchor !== 'bottom');
  const bottomGroup = railPanels.filter((p) => p.anchor === 'bottom');

  const endDrag = () => {
    setDragId(null);
    setDropTargetId(null);
  };

  // Drag-reorder the rail's top group (bottom-anchored panels are pinned).
  // Drop re-seats the dragged id before the target in the region's
  // arrangement — the same convention as the tab strip.
  const dragProps = (panel: PanelEntry) => ({
    draggable: panel.anchor !== 'bottom',
    onDragStart: (e: ReactDragEvent) => {
      if (panel.anchor === 'bottom') return;
      setDragId(panel.id);
      e.dataTransfer.effectAllowed = 'move';
      // Firefox refuses drags without payload; the id doubles as the source.
      e.dataTransfer.setData('text/plain', panel.id);
    },
    onDragOver: (e: ReactDragEvent) => {
      if (dragId === null || panel.anchor === 'bottom') return;
      e.preventDefault();
      setDropTargetId(panel.id);
    },
    onDrop: (e: ReactDragEvent) => {
      e.preventDefault();
      const from = e.dataTransfer.getData('text/plain');
      if (from && from !== panel.id && panel.anchor !== 'bottom') {
        const ids = railPanels.map((p) => p.id).filter((x) => x !== from);
        const at = ids.indexOf(panel.id);
        if (at === -1) ids.push(from);
        else ids.splice(at, 0, from);
        setPanelOrder(region, ids);
      }
      endDrag();
    },
    onDragEnd: endDrag,
  });

  const railButton = (panel: PanelEntry) => (
    <div
      key={panel.id}
      {...dragProps(panel)}
      className={cn(
        'rounded-md',
        dropTargetId === panel.id && dragId !== null && dragId !== panel.id && 'ring-1 ring-muted-foreground/40',
        dragId === panel.id && 'opacity-50',
      )}
    >
      <RailButton panel={panel} region={region} />
    </div>
  );

  return (
    <div
      className="flex h-full w-12 shrink-0 flex-col items-center gap-1 border-r bg-background py-2"
      data-testid={`panel-rail-${region}`}
      data-panel-rail-region={region}
    >
      {topGroup.map(railButton)}
      {(bottomGroup.length > 0 || railFooter) && (
        <>
          <div className="flex-1" />
          {bottomGroup.map(railButton)}
          {railFooter}
        </>
      )}
    </div>
  );
}
